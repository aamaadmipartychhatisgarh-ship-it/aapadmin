// The role of a Wing base name (the master's base role), accepting the spellings in use; null for anything else.
export function owRoleOfBase(baseName) {
  const b = norm(baseName).replace(/[.\-]/g, " ").replace(/\s+/g, " ").trim();
  if (/^(president|adhyaksh|adhyaksha|अध्यक्ष)$/.test(b)) return "president";
  if (/^(prabhari|प्रभारी|in ?charge)$/.test(b)) return "prabhari";
  if (/^(sang?h?a?than mantri|sangathan mantri|संगठन मंत्री)$/.test(b)) return "sangathan_mantri";
  return null;
}

