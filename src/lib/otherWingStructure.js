// (lib/vacancyDashboard) and through them the Tree Map, the vacancy lists and the WhatsApp message all read the same rules.
//
// Wings: exactly these 15 (Wing master names; there is no Wing called "Other"). Each keeps its own designations, members,
// vacancies and responsible people — nothing is combined across Wings.
// Structure (per Wing) — the only permitted designations, generated by the master as "<Level> <Role>, <Wing>":
