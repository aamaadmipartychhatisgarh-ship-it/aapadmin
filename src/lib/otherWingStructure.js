const norm = (s) => String(s || "").trim().replace(/\s+/g, " ").toLowerCase();
const OTHER_BY_NORM = new Map(OTHER_WINGS.map((w) => [norm(w.name), w]));
// The canonical Other Wing for a stored Wing name ("Youth Wing", "youth wing", "Youth" → "Youth Wing"), or null.
export function otherWingOf(name) {
  const n = norm(name);
  if (OTHER_BY_NORM.has(n)) return OTHER_BY_NORM.get(n).name;
  if (OTHER_BY_NORM.has(`${n} wing`)) return OTHER_BY_NORM.get(`${n} wing`).name;
  return null;
}

